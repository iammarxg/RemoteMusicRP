# Regenerate crates/app/tests/fixtures/update/fixture.txt: a tiny "release"
# signed by a THROWAWAY key made here and deleted afterwards, so the
# updater's success path is tested against real minisign output produced
# by scripts/sign-release.sh. Never use the real release key for this.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

minisign -G -W -f -p "$tmp/test.pub" -s "$tmp/test.key" >/dev/null
mkdir "$tmp/rel"
asset=remotemusicrp-test-target
printf 'pretend this is a release binary\n' > "$tmp/rel/$asset"
MINISIGN_KEY_FILE="$tmp/test.key" MINISIGN_PASSWORD='' \
  "$root/scripts/sign-release.sh" 9.9.9 "$tmp/rel" "$tmp/test.pub"

esc() { awk 'BEGIN{ORS="\\n"} {print}' "$1"; }
out="$root/crates/app/tests/fixtures/update/fixture.txt"
mkdir -p "$(dirname "$out")"
{
  echo "# Generated by scripts/make-update-fixture.sh (throwaway key)."
  echo "pubkey=$(sed -n 2p "$tmp/test.pub")"
  echo "asset=$asset"
  echo "binary=$(esc "$tmp/rel/$asset")"
  echo "binary_sig=$(esc "$tmp/rel/$asset.minisig")"
  echo "sums=$(esc "$tmp/rel/SHA256SUMS")"
  echo "sums_sig=$(esc "$tmp/rel/SHA256SUMS.minisig")"
} > "$out"
echo "wrote $out"
